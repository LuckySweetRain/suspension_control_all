"""NumPy/SciPy port of the existing ideal-force CarSim preview QP-MPC.

Inputs retain CarSim units and order; outputs are eight duplicated corner forces [N].
The MAT file is generated by build_quick_mpc_data.m, never re-tuned here.
"""

from __future__ import annotations

import os
from pathlib import Path

import numpy as np
from scipy.io import loadmat
from scipy.linalg import cho_solve

from native_solver import NativeSolver


class Controller:
    # Simulation-time hysteresis. Standstill disables preview actuation, while
    # passive damper forces remain present. These are integration policy values,
    # independent of the MATLAB QP weights and vehicle equilibrium reference.
    STOP_SPEED_MPS = 0.2
    RESUME_SPEED_MPS = 0.5
    TRANSITION_SECONDS = 0.5

    def __init__(self, path: str, active_enabled=None):
        self.active_enabled = (
            os.environ.get("SUSPENSION_ACTIVE_ENABLED", "1") != "0"
            if active_enabled is None
            else bool(active_enabled)
        )
        self.d = loadmat(path, simplify_cells=True)["data"]
        self.c = self.d["cfg"]
        if self.c["deployment"]["mode"] != "ideal_force":
            raise ValueError("This deployment supports ideal_force only")
        self.n = int(self.d["N"])
        self.a = np.asarray(self.d["Acon"], dtype=float)
        self.at = self.a.T.copy()
        self.gc = 2 * self.d["MyScaled"].T @ self.d["Qy"]
        self.gd = 2 * self.d["Dscaled"].T @ self.d["Rdu"]
        self.abs_tw = np.abs(self.d["Tw"])
        self.limit = np.asarray(self.c["force_limit"], dtype=float)
        self.native = (
            NativeSolver(self.a, self.d["qp_chol"])
            if Path(__file__).with_name("qp_native.so").is_file()
            else None
        )
        self.reset()

    def reset(self):
        self.origin = None
        self.prev = np.zeros(2)
        self.wx = np.zeros(2 * self.n)
        self.wz = np.zeros(self.a.shape[0])
        self.wy = np.zeros(self.a.shape[0])
        self.latched = False
        self.low_speed = False
        self.active_gain = 1.0
        self.motion_speed_mps = 0.0
        self.mode = "active"

    def clear_solver_warm_start(self):
        """Drop obsolete QP iterates, preserving the physical state origin."""
        self.wx.fill(0)
        self.wz.fill(0)
        self.wy.fill(0)

    def motion_status(self):
        return dict(
            active_enabled=self.active_enabled,
            mode=self.mode,
            speed_mps=self.motion_speed_mps,
            stop_speed_mps=self.STOP_SPEED_MPS,
            resume_speed_mps=self.RESUME_SPEED_MPS,
            transition_seconds=self.TRANSITION_SECONDS,
            active_gain=self.active_gain,
        )

    def state(self, y):
        jf = np.mean(y[[6, 8]])
        jr = np.mean(y[[7, 9]])
        if self.origin is None:
            self.origin = (y[0], y[3], jf, jr)
        z0, p0, f0, r0 = self.origin
        p = self.c["vehicle"]
        zb, dz = y[0] - z0, y[1] / 3.6
        theta = p["pitch_measurement_polarity"] * np.deg2rad(y[3] - p0)
        dt = p["pitch_measurement_polarity"] * np.deg2rad(y[4])
        return np.array(
            [
                zb,
                dz,
                theta,
                dt,
                zb + p["a"] * theta + (jf - f0) / 1000,
                dz + p["a"] * dt + np.mean(y[[10, 12]]) / 1000,
                zb - p["b"] * theta + (jr - r0) / 1000,
                dz - p["b"] * dt + np.mean(y[[11, 13]]) / 1000,
            ]
        )

    def preview(self, y):
        c = self.c
        p, r = c["preview"], c["robust"]
        v = abs(y[38]) / 3.6
        required = np.arange(self.n + 1) * v * c["control_dt"]
        distance = np.minimum(required, p["sensor_range_m"])
        sensor = self.d["road_sensor"]
        zf = np.interp(np.mean(y[[30, 32]]) + distance, sensor["station"], sensor["elevation"])
        zr = np.interp(np.mean(y[[31, 33]]) + distance, sensor["station"], sensor["elevation"])
        ds = np.diff(distance)
        sf = np.divide(np.diff(zf), ds, out=np.zeros(self.n), where=ds > np.finfo(float).eps)
        sr = np.divide(np.diff(zr), ds, out=np.zeros(self.n), where=ds > np.finfo(float).eps)
        w = np.column_stack((zf[:-1], v * sf, zr[:-1], v * sr)).ravel()
        gain = 1 + (p["far_uncertainty_gain"] - 1) * distance / p["sensor_range_m"]
        hb, sb = r["height_error_bound_m"] * gain, r["slope_error_bound"] * gain
        unseen = required > p["sensor_range_m"]
        hb[unseen] = r["unobserved_height_error_bound_m"]
        sb[unseen] = r["unobserved_slope_error_bound"]
        bound = np.column_stack((hb[:-1], v * sb[:-1], hb[:-1], v * sb[:-1])).ravel()
        meta = [distance[-1], required[-1], distance[-1] / max(required[-1], np.finfo(float).eps)]
        return w, bound, meta

    def solve(self, x0, w, bound):
        d, c = self.d, self.c
        dc = np.zeros(2 * self.n)
        dc[:2] = -self.prev
        dc /= d["dmax"]
        f = self.gc @ (d["Yx"] @ x0 + d["Yw"] @ w) + self.gd @ dc
        affine = (d["Tx"] @ x0 + d["Tw"] @ w) / d["travel_limit"]
        margin = np.zeros_like(affine)
        if c["robust"]["enabled"]:
            margin = np.minimum(
                self.abs_tw @ np.abs(bound) / d["travel_limit"],
                c["robust"]["max_travel_tightening_ratio"],
            )
        lo = np.concatenate((-np.ones(2 * self.n), -1 - dc, -1 + margin - affine))
        hi = np.concatenate((np.ones(2 * self.n), 1 - dc, 1 - margin - affine))
        opt = c["admm"]
        rho, sigma = opt["rho"], opt["sigma"]
        x, z, dual = self.wx.copy(), self.wz.copy(), self.wy.copy()
        converged = False
        _k = 0
        if self.native is not None:
            _k, converged = self.native.solve(f, lo, hi, x, z, dual, opt)
        for _k in range(1, (int(opt["max_iter"]) if self.native is None else 0) + 1):
            old_x, old_z = x, z
            rhs = -f + sigma * x + rho * (self.at @ (z - dual))
            x = cho_solve((d["qp_chol"], False), rhs, check_finite=False)
            ax = self.a @ x
            z = np.clip(ax + dual, lo, hi)
            dual = dual + ax - z
            primal = np.max(np.abs(ax - z))
            dr = np.max(np.abs(rho * (self.at @ (z - old_z)) + sigma * (x - old_x)))
            ep = opt["abs_tol"] + opt["rel_tol"] * max(np.max(np.abs(ax)), np.max(np.abs(z)))
            ed = opt["abs_tol"] + opt["rel_tol"] * np.max(np.abs(self.at @ dual))
            if primal <= ep and dr <= ed:
                converged = True
                break
        ax = self.a @ x
        self.wx = np.concatenate((x[2:], x[-2:]))
        self.wz, self.wy = z, dual
        force = np.clip(d["force_scale"][:2] * x[:2], -self.limit, self.limit)
        rate = np.asarray(c["force_rate_limit"]) * c["control_dt"]
        force = np.clip(force, self.prev - rate, self.prev + rate)
        violation = max(0.0, float(np.max(ax - hi)), float(np.max(lo - ax)))
        return force, [_k, violation, float(converged), float(np.max(margin))]

    def step(self, exports, external_preview=None, contact_active=False, lateral_speed_mps=0.0):
        y = np.asarray(exports, dtype=float)
        if y.shape == (77,):
            y = y[38:77]
        if y.shape != (39,) or not np.all(np.isfinite(y)):
            raise ValueError("Expected 39 or 77 finite CarSim exports")
        if not np.isfinite(lateral_speed_mps):
            raise ValueError("Expected finite lateral speed")
        x = self.state(y)
        if external_preview is None:
            w, bound, meta = self.preview(y)
        else:
            w, bound, meta = external_preview[:3]
            if len(external_preview) == 4:
                correction = np.asarray(external_preview[3], dtype=float)
                if correction.shape != (8,) or not np.all(np.isfinite(correction)):
                    raise ValueError("Invalid road-frame state correction")
                x = x - correction
        if (
            np.shape(w) != (4 * self.n,)
            or np.shape(bound) != (4 * self.n,)
            or not np.all(np.isfinite(w))
            or not np.all(np.isfinite(bound))
        ):
            raise ValueError("Invalid external image preview")
        self.motion_speed_mps = float(np.hypot(y[38] / 3.6, lateral_speed_mps))
        was_low_speed = self.low_speed
        if self.motion_speed_mps <= self.STOP_SPEED_MPS:
            self.low_speed = True
        elif self.motion_speed_mps >= self.RESUME_SPEED_MPS:
            self.low_speed = False
        if self.low_speed != was_low_speed:
            self.clear_solver_warm_start()

        if not self.active_enabled:
            # Explicit user selection: retain the replacement passive damper,
            # rather than zeroing the complete CarSim suspension import.
            force, info = np.zeros(2), [0, 0.0, 0.0, 0.0]
            self.active_gain = 0.0
            self.clear_solver_warm_start()
            self.mode = "disabled_passive"
        elif self.latched or contact_active:
            # Passive suspension during contact response; this is an explicit
            # collision supervisor, distinct from a QP failure/fallback latch.
            force, info = np.zeros(2), [0, 0.0, 0.0, 0.0]
            self.active_gain = 0.0
            self.clear_solver_warm_start()
            self.mode = "qp_fallback" if self.latched else "supervised_passive"
        elif self.low_speed:
            # No QP is solved at standstill. Slew the last actual axle commands
            # to zero in at most 0.5 s, rather than exciting a parked body with
            # camera height residuals or keeping a stale preview force alive.
            slew = (
                np.minimum(
                    self.limit / self.TRANSITION_SECONDS,
                    np.asarray(self.c["force_rate_limit"]),
                )
                * self.c["control_dt"]
            )
            force = self.prev - np.clip(self.prev, -slew, slew)
            info = [0, 0.0, 0.0, 0.0]
            self.active_gain = 0.0
            self.mode = "low_speed_ramp_down" if np.any(force) else "standstill_passive"
        else:
            force, info = self.solve(x, w, bound)
            self.active_gain = min(
                1.0, self.active_gain + self.c["control_dt"] / self.TRANSITION_SECONDS
            )
            force *= self.active_gain
            # Blending must respect the configured force slew limit too.
            rate = np.asarray(self.c["force_rate_limit"]) * self.c["control_dt"]
            if self.active_gain < 1.0:
                rate = np.minimum(rate, self.limit * self.c["control_dt"] / self.TRANSITION_SECONDS)
            force = np.clip(force, self.prev - rate, self.prev + rate)
            self.mode = "restart_ramp_up" if self.active_gain < 1.0 else "active"
        # Match the MATLAB runtime: an iteration-limited feasible solution is
        # usable after force/rate projection. Keep convergence visible in diag[4].
        # Reject a materially infeasible solution (normalized bound error >0.5%).
        if not np.all(np.isfinite(force)) or info[1] > 0.005:
            self.latched = True
        if self.latched:
            force = np.zeros(2)
            self.active_gain = 0.0
            self.mode = "qp_fallback"
        self.prev = force
        total = self.c["carsim_damper_gain"] * y[22:26]
        total += self.c["active_scale"] * 0.5 * force[[0, 1, 0, 1]]
        total = np.clip(total, -self.c["corner_force_limit"], self.c["corner_force_limit"])
        diag = [*force, *info[:3], *meta[:2], 1.0, meta[2], info[3]]
        return np.tile(total, 2).tolist(), diag, self.latched
